export type ProductCategory = 'physical' | 'digital';
export type Product = {
  id: string;
  slug: string;
  name: string;
  category: ProductCategory;
  collection: string;
  price: number;
  image: string;
  badge?: string;
  color: string;
  description: string;
  includes: string[];
  stock: number;
};
export type TaskStatus = 'available' | 'in_progress' | 'under_review' | 'revision' | 'completed' | 'cancelled';
export type Submission = { name: string; size: number; submittedAt: number; by: string };
export type Task = {
  id: string;
  title: string;
  category: string;
  description: string;
  reward: number;
  durationHours: number;
  status: TaskStatus;
  postedAt: number;
  art: string;
  tone: string;
  skills: string[];
  deliverables: string[];
  brief: string;
  assignedTo?: string;
  assigneeName?: string;
  claimedAt?: number;
  deadlineAt?: number;
  submissions: Submission[];
};
export type User = { id: string; name: string; email: string; role: 'designer' | 'admin'; joinedAt: number };
export type Penalty = { id: string; userId: string; taskId: string; level: number; hours: number; at: number; until: number | null };
export type CartItem = { productId: string; quantity: number };
export type Order = { id: string; total: number; at: number; items: CartItem[]; customerName: string; email: string; address: string; payment: string };
